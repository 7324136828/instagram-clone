test.describe('on the smallest supported viewport (320px)', () => {
  test.use({ viewport: { width: 320, height: 568 } });

  test('the header with its import button fits, before and after an import', async ({ page }) => {
    await openApp(page);
    const header = page.locator('.mobile-header');
    const expectHeaderFits = async () => {
      expect(await sidewaysOverflow(page)).toBeLessThanOrEqual(0);
      for (const name of ['Import Instagram export', 'Toggle theme', 'Notifications', 'Messages']) {
        const box = await header.getByRole('button', { name }).boundingBox();
        expect(box, name).not.toBeNull();
        expect(box!.x, name).toBeGreaterThanOrEqual(0);
        expect(box!.x + box!.width, name).toBeLessThanOrEqual(320);
      }
      // The wordmark does not run into the first icon.
      const wordmark = await header.getByRole('button', { name: 'Instagram', exact: true }).boundingBox();
      const first = await header.getByRole('button', { name: 'Import Instagram export' }).boundingBox();
      expect(wordmark!.x + wordmark!.width).toBeLessThanOrEqual(first!.x - 4);
      // The tab bar keeps all of its items on screen, the own profile (the last one) included.
      const profile = await mainNav(page).getByRole('button', { name: 'Profile' }).boundingBox();
      expect(profile!.x + profile!.width).toBeLessThanOrEqual(320);
    };
    await expectHeaderFits();

    await page.getByTestId('import-open-mobile').click();
    await page.getByTestId('import-archive-input').setInputFiles(fixture('export-basic.zip'));
    await expectImportSuccess(page, 'Imported 6 of 6 posts from export-basic.zip');
    await viewFeed(page);
    await expectHeaderFits();
  });
});
