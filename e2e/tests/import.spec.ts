/**
 * Like writeExport, but with `count` posts that each have a picture file of their own (copies of
 * the three test cards): more than a screenful, so most of them are not loaded right away.
 */
function writePictureExport(testInfo: TestInfo, name: string, count: number): PictureExport {
  const cards: Array<{ file: string; ext: string; color: Rgb }> = [
    { file: 'post1.jpg', ext: 'jpg', color: COLOR.post1 },
    { file: 'post2.png', ext: 'png', color: COLOR.post2 },
    { file: 'post3.webp', ext: 'webp', color: COLOR.post3 },
  ];
  const dir = testInfo.outputPath(name);
  mkdirSync(join(dir, 'posts'), { recursive: true });
  const posts: PictureExport['posts'] = [];
  const entries: Array<Record<string, unknown>> = [];
  for (let i = 0; i < count; i++) {
    const picture = cards[i % cards.length];
    const number = String(i + 1).padStart(2, '0');
    const image = `posts/picture${number}.${picture.ext}`;
    copyFileSync(fixture(`export-basic/posts/${picture.file}`), join(dir, image));
    posts.push({ id: `FXTkeep${number}`, color: picture.color });
    entries.push({ id: `FXTkeep${number}`, image, user: { username: BAKERY }, caption: `Picture ${number}`, comment_count: 0 });
  }
  writeFileSync(join(dir, 'post.json'), JSON.stringify({ format: 'instagram-export', version: 1, posts: entries }, null, 2));
  return { dir, posts };
}

function crc32(data: Uint8Array): number {
  let crc = 0xffffffff;
  for (const byte of data) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/**
 * Packs an export folder into a zip whose members are stored, not compressed (what "zip -0" and
 * several tools do for pictures). The importer reads such members straight out of the file.
 */
function writeStoredZip(dir: string, zipPath: string): void {
  const names = ['post.json', ...readdirSync(join(dir, 'posts')).sort().map((file) => `posts/${file}`)];
  const members: Buffer[] = [];
  const directory: Buffer[] = [];
  let offset = 0;
  for (const name of names) {
    const data = readFileSync(join(dir, name));
    const nameBytes = Buffer.from(name, 'utf8');
    const crc = crc32(data);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(0, 8); // method 0: stored
    local.writeUInt16LE(0x0021, 12); // 1980-01-01
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(0, 10);
    central.writeUInt16LE(0x0021, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBytes.length, 28);
    central.writeUInt32LE(offset, 42);

    members.push(local, nameBytes, data);
    directory.push(central, nameBytes);
    offset += local.length + nameBytes.length + data.length;
  }
  const directoryBytes = Buffer.concat(directory);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(names.length, 8);
  end.writeUInt16LE(names.length, 10);
  end.writeUInt32LE(directoryBytes.length, 12);
  end.writeUInt32LE(offset, 16);
  writeFileSync(zipPath, Buffer.concat([...members, directoryBytes, end]));
}

