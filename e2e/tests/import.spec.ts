/** The <img> has loaded and decoded a real picture (images are lazy, so it is scrolled to first). */
async function expectDecoded(image: Locator): Promise<void> {
  await expect(image).toHaveCount(1);
  await image.scrollIntoViewIfNeeded();
  await expect
    .poll(() => image.evaluate((el: HTMLImageElement) => (el.complete ? el.naturalWidth : 0)), {
      message: 'image should be decoded (naturalWidth > 0)',
    })
    .toBeGreaterThan(0);
}

/** Reads one background pixel of the decoded picture; lossy codecs get a tolerance. */
async function expectColor(image: Locator, expected: Rgb, tolerance = 14): Promise<void> {
  await expectDecoded(image);
  const actual = await image.evaluate(async (el: HTMLImageElement) => {
    await el.decode();
    const canvas = document.createElement('canvas');
    canvas.width = el.naturalWidth;
    canvas.height = el.naturalHeight;
    const context = canvas.getContext('2d');
    if (!context) throw new Error('no 2d context');
    context.drawImage(el, 0, 0);
    // Inside the frame, outside the circle and the label: plain background.
    const pixel = context.getImageData(60, 200, 1, 1).data;
    return [pixel[0], pixel[1], pixel[2]];
  });
  for (let channel = 0; channel < 3; channel++) {
    expect(
      Math.abs(actual[channel] - expected[channel]),
      `pixel rgb(${actual.join(', ')}) should be close to rgb(${expected.join(', ')})`,
    ).toBeLessThanOrEqual(tolerance);
  }
}

