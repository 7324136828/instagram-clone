/** Relative luminance (0 = black, 1 = white) of the page background. */
async function pageLuminance(page: Page): Promise<number> {
  return page.evaluate(() => {
    const parts = (getComputedStyle(document.body).backgroundColor.match(/[\d.]+/g) ?? []).map(Number);
    const [r, g, b] = parts.slice(0, 3).map((channel) => {
      const c = channel / 255;
      return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
    });
    return 0.2126 * r + 0.7152 * g + 0.0722 * b;
  });
}

/**
 * WCAG contrast ratio between the text colour of the first match and the background it sits on
 * (the nearest ancestor with an opaque background colour).
 */
async function textContrast(locator: Locator): Promise<number> {
  return locator.first().evaluate((el) => {
    const parse = (value: string) => (value.match(/[\d.]+/g) ?? []).map(Number);
    const luminance = (rgb: number[]) => {
      const [r, g, b] = rgb.slice(0, 3).map((channel) => {
        const c = channel / 255;
        return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
      });
      return 0.2126 * r + 0.7152 * g + 0.0722 * b;
    };
    let background = [255, 255, 255];
    for (let node: Element | null = el; node; node = node.parentElement) {
      const color = parse(getComputedStyle(node).backgroundColor);
      if (color.length >= 3 && (color.length === 3 || color[3] >= 0.95)) {
        background = color;
        break;
      }
    }
    const text = luminance(parse(getComputedStyle(el).color));
    const back = luminance(background);
    return (Math.max(text, back) + 0.05) / (Math.min(text, back) + 0.05);
  });
}

