/**
 * Name of the import kept in IndexedDB ('ig-clone-import' / store 'import' / key 'meta', see
 * frontend/src/import/persist.ts), or null. Saving is asynchronous and has no UI signal, so the
 * reload tests wait on this instead of sleeping.
 */
async function savedImportName(page: Page): Promise<string | null> {
  return page.evaluate(async () => {
    const known = await indexedDB.databases();
    // Opening a database that does not exist yet would create it without the app's object store.
    if (!known.some((db) => db.name === 'ig-clone-import')) return null;
    return new Promise<string | null>((resolve) => {
      const open = indexedDB.open('ig-clone-import');
      open.onerror = () => resolve(null);
      open.onsuccess = () => {
        const db = open.result;
        if (!db.objectStoreNames.contains('import')) {
          db.close();
          resolve(null);
          return;
        }
        const request = db.transaction('import', 'readonly').objectStore('import').get('meta');
        request.onsuccess = () => {
          const meta = request.result as { sourceName?: string } | undefined;
          db.close();
          resolve(meta?.sourceName ?? null);
        };
        request.onerror = () => {
          db.close();
          resolve(null);
        };
      };
    });
  });
}

