/**
 * Writes a throwaway export folder (post.json next to posts/) into the test's output directory
 * and returns its path. posts/ holds post1.jpg, post2.png and post3.webp of export-basic.
 */
function writeExport(testInfo: TestInfo, name: string, posts: Array<Record<string, unknown>>): string {
  const dir = testInfo.outputPath(name);
  mkdirSync(join(dir, 'posts'), { recursive: true });
  for (const picture of ['post1.jpg', 'post2.png', 'post3.webp']) {
    copyFileSync(fixture(`export-basic/posts/${picture}`), join(dir, 'posts', picture));
  }
  writeFileSync(join(dir, 'post.json'), JSON.stringify({ format: 'instagram-export', version: 1, posts }, null, 2));
  return dir;
}

