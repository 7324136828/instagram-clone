interface ReadGate {
  hold: () => void;
  release: () => void;
}

/**
 * Lets a test pause the importer: while the gate is held, every file read (Blob.arrayBuffer)
 * waits. Must be installed before the page loads.
 */
async function installReadGate(page: Page): Promise<void> {
  await page.addInitScript(() => {
    const original = Blob.prototype.arrayBuffer;
    let held = false;
    let waiting: Array<() => void> = [];
    const gate: ReadGate = {
      hold: () => { held = true; },
      release: () => {
        held = false;
        for (const resume of waiting) resume();
        waiting = [];
      },
    };
    (window as unknown as { readGate: ReadGate }).readGate = gate;
    Blob.prototype.arrayBuffer = async function arrayBuffer(this: Blob) {
      if (held) await new Promise<void>((resolve) => { waiting.push(resolve); });
      return original.call(this);
    };
  });
}

const holdReads = (page: Page) => page.evaluate(() => (window as unknown as { readGate: ReadGate }).readGate.hold());
const releaseReads = (page: Page) => page.evaluate(() => (window as unknown as { readGate: ReadGate }).readGate.release());

interface Box { left: number; top: number; right: number; bottom: number }

/** Bounding box of the first element matching the selector, or null when it is not rendered. */
async function boxOf(page: Page, selector: string): Promise<Box | null> {
  return page.evaluate((sel) => {
    const el = document.querySelector(sel);
    if (!el) return null;
    const rect = el.getBoundingClientRect();
    if (rect.width === 0 || rect.height === 0) return null;
    return { left: rect.left, top: rect.top, right: rect.right, bottom: rect.bottom };
  }, selector);
}

function overlaps(a: Box | null, b: Box | null): boolean {
  if (!a || !b) return false;
  return a.left < b.right && b.left < a.right && a.top < b.bottom && b.top < a.bottom;
}

/** True when keyboard focus is inside an element matching the selector. */
const focusIsInside = (page: Page, selector: string) =>
  page.evaluate((sel) => !!document.activeElement?.closest(sel), selector);

